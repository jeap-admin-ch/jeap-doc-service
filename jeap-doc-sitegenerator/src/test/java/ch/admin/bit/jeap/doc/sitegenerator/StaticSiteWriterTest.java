package ch.admin.bit.jeap.doc.sitegenerator;

import ch.admin.bit.jeap.doc.domain.SitePart;
import ch.admin.bit.jeap.doc.domain.Site;
import ch.admin.bit.jeap.doc.domain.custom.CustomProperties;
import ch.admin.bit.jeap.doc.domain.custom.CustomSet;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.Instant;
import java.util.List;
import java.util.Optional;
import java.util.stream.Stream;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * A static site is its uploaded tree, published as it is: its folders and their {@code _category_.json} are the
 * navigation, and nothing is generated into it but a root page where it brings none.
 */
class StaticSiteWriterTest {

    private static final Instant GENERATED_AT = Instant.parse("2026-10-02T09:00:00Z");
    private static final Site HANDBOOK = new Site("handbook", "Handbook", null, null, null, "jeap", List.of(), true,
            false);

    @TempDir
    Path content;

    @Test
    void write_thenTheTreeIsWrittenAsItIsWithItsFoldersAsTheNavigation() throws IOException {
        UploadedTree tree = new UploadedTree("handbook")
                .page("index.md", "---\ntitle: Welcome\n---\n\n# Welcome\n")
                .file("intro/_category_.json", "{\"label\": \"Introduction\", \"position\": 1}"
                        .getBytes(StandardCharsets.UTF_8))
                .page("intro/01-why.md", "---\ntitle: Why\nslug: /elsewhere\n---\n\nBecause.\n")
                .page("working-agreements/reviews.md", "# Reviews\n\nTwo pairs of eyes.\n")
                .file("working-agreements/img/flow.png", new byte[]{1, 2, 3});

        assertThat(tree.writer().write(HANDBOOK, shell(), content, GENERATED_AT).models()).isEmpty();

        Path written = content.resolve(SiteSources.SINGLE_TREE);
        assertThat(filesBelow(written)).containsExactlyInAnyOrder("index.md", "intro/_category_.json",
                "intro/01-why.md", "working-agreements/reviews.md", "working-agreements/img/flow.png");
        assertThat(Files.readString(written.resolve("intro/_category_.json")))
                .isEqualTo("{\"label\":\"Introduction\",\"position\":1}");
        assertThat(Files.readAllBytes(written.resolve("working-agreements/img/flow.png")))
                .containsExactly(1, 2, 3);
        String why = Files.readString(written.resolve("intro/01-why.md"));
        assertThat(why).contains("title: Why").contains("doc_status: custom")
                .contains("doc_source_repository: https://git.example.ch/handbook")
                .describedAs("a page does not decide its own URL").doesNotContain("slug")
                .endsWith("Because.\n");
        assertThat(Files.readString(written.resolve("index.md")))
                .describedAs("the tree's own root page, and no generated one")
                .contains("# Welcome").doesNotContain("generated by the jEAP Doc Service");
    }

    @Test
    void write_whenTheTreeBringsNoRootPage_thenOneIsGenerated() throws IOException {
        new UploadedTree("handbook").page("intro/why.md", "# Why\n")
                .writer().write(HANDBOOK, shell(), content, GENERATED_AT);

        assertThat(Files.readString(content.resolve(SiteSources.SINGLE_TREE).resolve("index.md")))
                .contains("slug: /").contains("Its pages are in the navigation.")
                .doesNotContain("doc_environment").doesNotContain("{{");
    }

    /** A numbered index is a page of its own to Docusaurus, at /index, so the root page is still generated. */
    @Test
    void write_whenTheTreeBringsANumberedIndex_thenTheRootPageIsStillGenerated() throws IOException {
        new UploadedTree("handbook").page("00-index.md", "# Contents\n")
                .writer().write(HANDBOOK, shell(), content, GENERATED_AT);

        Path tree = content.resolve(SiteSources.SINGLE_TREE);
        assertThat(filesBelow(tree)).containsExactlyInAnyOrder("00-index.md", "index.md");
        assertThat(Files.readString(tree.resolve("index.md"))).contains("Its pages are in the navigation.");
    }

    @Test
    void write_whenNothingHasBeenUploaded_thenTheSiteIsItsRootPage() throws IOException {
        new StaticSiteWriter(new NoCustomDocumentation(), new NoCustomStorage(), new CustomProperties())
                .write(HANDBOOK, shell(), content, GENERATED_AT);

        Path tree = content.resolve(SiteSources.SINGLE_TREE);
        assertThat(filesBelow(tree)).containsExactly("index.md");
        assertThat(Files.readString(tree.resolve("index.md"))).contains("Nothing has been uploaded to it yet.");
    }

    /** A page that is not UTF-8 is left out rather than repaired, as every uploaded page is. */
    @Test
    void write_whenAPageIsNotUtf8_thenItIsLeftOutAndTheRestIsWritten() throws IOException {
        new UploadedTree("handbook")
                .file("broken.md", new byte[]{(byte) 0xC3, (byte) 0x28})
                .page("fine.md", "# Fine\n")
                .writer().write(HANDBOOK, shell(), content, GENERATED_AT);

        assertThat(filesBelow(content.resolve(SiteSources.SINGLE_TREE))).contains("fine.md")
                .doesNotContain("broken.md");
    }

    /** A set stored before the upload refused one name for a file and a folder loses that page, not the build. */
    @Test
    void write_whenAPageLiesBelowAFile_thenThatPageIsLeftOutAndTheRestIsWritten() throws IOException {
        new UploadedTree("handbook")
                .file("guide", new byte[]{1})
                .page("guide/setup.md", "# Setup\n")
                .page("fine.md", "# Fine\n")
                .writer().write(HANDBOOK, shell(), content, GENERATED_AT);

        assertThat(filesBelow(content.resolve(SiteSources.SINGLE_TREE))).contains("guide", "fine.md")
                .doesNotContain("guide/setup.md");
    }

    /**
     * Docusaurus fails the whole build on a category it cannot resolve, so a folder's {@code _category_.json}
     * keeps only its label, position and folding, and one that is no JSON object is left out.
     */
    @Test
    void write_whenACategorySaysMoreThanItsLabel_thenOnlyTheLabelPositionAndFoldingAreWritten() throws IOException {
        new UploadedTree("handbook")
                .page("intro/_category_.json", "{\"label\": \"Intro\", \"link\": {\"type\": \"doc\", "
                                               + "\"id\": \"missing\"}, \"position\": \"first\", "
                                               + "\"collapsed\": false, \"customProps\": {}}")
                .page("intro/why.md", "# Why\n")
                .page("broken/_category_.json", "{\"label\": ")
                .page("broken/how.md", "# How\n")
                .writer().write(HANDBOOK, shell(), content, GENERATED_AT);

        Path written = content.resolve(SiteSources.SINGLE_TREE);
        assertThat(Files.readString(written.resolve("intro/_category_.json")))
                .isEqualTo("{\"label\":\"Intro\",\"collapsed\":false}");
        assertThat(filesBelow(written)).contains("intro/why.md", "broken/how.md")
                .doesNotContain("broken/_category_.json");
    }

    /** A tree whose bundle is gone publishes no page, and its root page does not point to a navigation. */
    @Test
    void write_whenTheBundleIsGone_thenTheRootPageSaysTheUploadCouldNotBePublished() throws IOException {
        UploadedTree tree = new UploadedTree("handbook").page("intro/why.md", "# Why\n");
        NoCustomStorage gone = new NoCustomStorage() {
            @Override
            public Optional<OpenedBundle> open(CustomSet set) {
                return Optional.empty();
            }
        };
        new StaticSiteWriter(tree.documentation(), gone, new CustomProperties())
                .write(HANDBOOK, shell(), content, GENERATED_AT);

        Path written = content.resolve(SiteSources.SINGLE_TREE);
        assertThat(filesBelow(written)).containsExactly("index.md");
        assertThat(Files.readString(written.resolve("index.md")))
                .contains("could not be published").doesNotContain("navigation");
    }

    private static SitePart shell() {
        return SitePart.wholeSiteOf(HANDBOOK);
    }

    private static List<String> filesBelow(Path tree) throws IOException {
        try (Stream<Path> files = Files.walk(tree)) {
            return files.filter(Files::isRegularFile)
                    .map(file -> tree.relativize(file).toString().replace('\\', '/'))
                    .toList();
        }
    }
}
