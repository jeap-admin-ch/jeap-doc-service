package ch.admin.bit.jeap.doc.markdown;

import org.junit.jupiter.api.Test;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.CsvSource;

import java.util.List;

import static ch.admin.bit.jeap.doc.markdown.FrontMatter.frontMatter;
import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

class MarkdownWriterTest {

    @Test
    void frontMatter_isTheFirstThingOnThePage_andEveryValueIsQuoted() {
        String page = new MarkdownWriter()
                .frontMatter(frontMatter()
                        .put("title", "jEAP: Documentation")
                        .put("sidebar_position", 5)
                        .put("doc_status", "generated"))
                .heading(1, "jEAP: Documentation")
                .text();

        assertThat(page).isEqualTo("""
                ---
                title: "jEAP: Documentation"
                sidebar_position: 5
                doc_status: "generated"
                ---

                # jEAP: Documentation
                """);
    }

    @Test
    void frontMatter_whenSomethingIsAlreadyWritten_thenItIsRefused() {
        MarkdownWriter writer = new MarkdownWriter().heading(1, "Too late");
        FrontMatter frontMatter = frontMatter().put("title", "x");
        assertThatThrownBy(() -> writer.frontMatter(frontMatter))
                .isInstanceOf(IllegalStateException.class);
    }

    @Test
    void blocks_areSeparatedByExactlyOneBlankLine() {
        String page = new MarkdownWriter()
                .heading(1, "Title")
                .paragraph("First.")
                .heading(2, "Section")
                .paragraph("Second.")
                .text();

        assertThat(page).isEqualTo("""
                # Title

                First.

                ## Section

                Second.
                """);
    }

    @Test
    void table_writesTheAlignmentRowAndEscapesThePipeInACell() {
        String page = new MarkdownWriter()
                .table(List.of("Component", "Description"),
                        List.of(List.of(Md.code("orders-foo"), Md.text("does a | b")),
                                List.of(Md.code("orders-bar"), Markdown.EMPTY)))
                .text();

        assertThat(page).isEqualTo("""
                | Component | Description |
                | --- | --- |
                | `orders-foo` | does a \\| b |
                | `orders-bar` | - |
                """);
    }

    @Test
    void table_flattensALineBreakInACell() {
        String page = new MarkdownWriter()
                .table(List.of("A"), List.of(List.of(Md.text("first\nsecond"))))
                .text();
        assertThat(page).contains("| first second |");
    }

    /**
     * A row of the wrong width renders as a table with a missing cell rather than as an error, which is exactly
     * the kind of defect nobody reports.
     */
    @Test
    void table_whenARowDoesNotMatchTheHeader_thenItFails() {
        MarkdownWriter writer = new MarkdownWriter();
        List<String> header = List.of("A", "B");
        List<List<Markdown>> rows = List.of(List.of(Md.text("only one")));
        assertThatThrownBy(() -> writer.table(header, rows))
                .isInstanceOf(IllegalArgumentException.class)
                .hasMessageContaining("2 columns");
    }

    @Test
    void bulletList_writesNothingWhenThereIsNothing() {
        assertThat(new MarkdownWriter().bulletList(List.of()).text()).isEmpty();
    }

    @Test
    void fence_passesTheBodyThroughUntouched() {
        String page = new MarkdownWriter().fence("plantuml", "@startuml\ncomponent \"a|b\"\n@enduml").text();
        assertThat(page).isEqualTo("""
                ```plantuml
                @startuml
                component "a|b"
                @enduml
                ```
                """);
    }

    @Test
    void fence_whenTheBodyCarriesAFence_thenTheOuterOneIsLonger() {
        String page = new MarkdownWriter().fence("dot", "a\n```\nb").text();
        assertThat(page).startsWith("````dot\n").endsWith("````\n");
    }

    @Test
    void fence_whenTheLanguageIsNotAWord_thenItIsRefused() {
        MarkdownWriter writer = new MarkdownWriter();
        assertThatThrownBy(() -> writer.fence("Plant UML", "x")).isInstanceOf(IllegalArgumentException.class);
    }

    @Test
    void admonition_isWrittenAsDocusaurusReadsIt() {
        String page = new MarkdownWriter()
                .admonition("info", "Generated page", Md.text("Generated by the jEAP Doc Service."))
                .text();

        assertThat(page).isEqualTo("""
                :::info[Generated page]

                Generated by the jEAP Doc Service.

                :::
                """);
    }

    @Test
    void admonition_whenThereIsNothingToSay_thenItIsRefused() {
        MarkdownWriter writer = new MarkdownWriter();
        assertThatThrownBy(() -> writer.admonition("info", "Title", Markdown.EMPTY))
                .isInstanceOf(IllegalArgumentException.class);
    }

    @Test
    void details_isWrittenAsADirectiveTheSiteFolds() {
        String page = new MarkdownWriter()
                .details("Version 1.0.0", body -> body.fence("java", "record Key(String id) {}"))
                .text();

        assertThat(page).isEqualTo("""
                :::details[Version 1.0.0]

                ```java
                record Key(String id) {}
                ```

                :::
                """);
    }

    @Test
    void details_escapesTheSummary() {
        String page = new MarkdownWriter().details("<script>] *x*", body -> body.paragraph("Inside.")).text();

        assertThat(page).startsWith(":::details[" + Md.text("<script>] *x*").value() + "]");
    }

    /** A directive inside the fold would otherwise close it at its own closing line. */
    @Test
    void details_whenTheBodyHoldsADirective_thenTheFoldIsMarkedWithMoreColons() {
        String page = new MarkdownWriter()
                .details("Notes", body -> body.admonition("note", "Inside", Md.text("Careful.")))
                .text();

        assertThat(page).startsWith("::::details[Notes]").endsWith("\n::::\n").contains("\n:::note[Inside]\n");
    }

    @Test
    void details_whenThereIsNothingToFoldOrNoSummary_thenItIsRefused() {
        MarkdownWriter writer = new MarkdownWriter();
        assertThatThrownBy(() -> writer.details("Empty", body -> { }))
                .isInstanceOf(IllegalArgumentException.class);
        assertThatThrownBy(() -> writer.details(" ", body -> body.paragraph("x")))
                .isInstanceOf(IllegalArgumentException.class);
    }

    @Test
    void groupedTable_isWrittenAsNestedDirectivesTheSiteBuildsATableFrom() {
        String page = new MarkdownWriter()
                .groupedTable("Version", "", "Schema", List.of(
                        new MarkdownWriter.Group(Md.code("1.0.0"), List.of(
                                new MarkdownWriter.Row(Md.text("Key"), cell -> cell.paragraph("Key.avdl")),
                                new MarkdownWriter.Row(Md.text("Value"), cell -> cell.paragraph("Value.avdl"))))))
                .text();

        assertThat(page).isEqualTo("""
                :::::grouped-table

                :::column[Version]
                :::

                :::column[]
                :::

                :::column[Schema]
                :::

                ::::group[`1.0.0`]

                :::row[Key]

                Key.avdl

                :::

                :::row[Value]

                Value.avdl

                :::

                ::::

                :::::
                """);
    }

    /** A fold in a cell has its own marker, so every level around it takes one more colon. */
    @Test
    void groupedTable_whenACellHoldsAFold_thenEveryLevelAroundItIsMarkedLonger() {
        String page = new MarkdownWriter()
                .groupedTable("Version", "", "Schema", List.of(new MarkdownWriter.Group(Md.text("1.0.0"), List.of(
                        new MarkdownWriter.Row(Md.text("Value"),
                                cell -> cell.details("Schema", fold -> fold.fence("java", "string id;")))))))
                .text();

        assertThat(page).startsWith("::::::grouped-table\n")
                .contains("\n:::::group[1.0.0]\n")
                .contains("\n::::row[Value]\n")
                .contains("\n:::details[Schema]\n")
                .endsWith("\n::::::\n");
    }

    @Test
    void groupedTable_escapesItsLabels() {
        String page = new MarkdownWriter()
                .groupedTable("<b>]", "", "Schema", List.of(new MarkdownWriter.Group(Md.text("1.0.0"), List.of(
                        new MarkdownWriter.Row(Md.text("]*x*"), cell -> cell.paragraph("text"))))))
                .text();

        assertThat(page).contains(":::column[" + Md.text("<b>]").value() + "]")
                .contains(":::row[" + Md.text("]*x*").value() + "]");
    }

    @Test
    void groupedTable_whenThereIsNothingToShow_thenItIsRefused() {
        MarkdownWriter writer = new MarkdownWriter();
        assertThatThrownBy(() -> writer.groupedTable("A", "B", "C", List.of()))
                .isInstanceOf(IllegalArgumentException.class);
        List<MarkdownWriter.Group> noRow = List.of(new MarkdownWriter.Group(Md.text("1.0.0"), List.of()));
        assertThatThrownBy(() -> writer.groupedTable("A", "B", "C", noRow))
                .isInstanceOf(IllegalArgumentException.class);
        List<MarkdownWriter.Group> emptyCell = List.of(new MarkdownWriter.Group(Md.text("1.0.0"),
                List.of(new MarkdownWriter.Row(Md.text("Key"), cell -> { }))));
        assertThatThrownBy(() -> writer.groupedTable("A", "B", "C", emptyCell))
                .isInstanceOf(IllegalArgumentException.class);
    }

    @Test
    void hasContent_ignoresTheFrontMatter() {
        MarkdownWriter writer = new MarkdownWriter().frontMatter(frontMatter().put("title", "x"));
        assertThat(writer.hasContent()).isFalse();
        writer.paragraph("Something.");
        assertThat(writer.hasContent()).isTrue();
    }

    @Test
    void paragraph_whenThereIsNothing_thenNothingIsWritten() {
        assertThat(new MarkdownWriter().paragraph(Markdown.EMPTY).text()).isEmpty();
    }

    @Test
    void paragraphOrNothing_saysSoRatherThanLeavingTheSectionEmpty() {
        assertThat(new MarkdownWriter().paragraphOrNothing(Markdown.EMPTY, "None.").text()).isEqualTo("None.\n");
    }

    @Test
    void heading_isBetweenOneAndFour() {
        MarkdownWriter writer = new MarkdownWriter();
        assertThatThrownBy(() -> writer.heading(0, "x")).isInstanceOf(IllegalArgumentException.class);
        assertThatThrownBy(() -> writer.heading(5, "x")).isInstanceOf(IllegalArgumentException.class);
    }

    /**
     * An imported description is free text, and a description that happens to begin with a bullet, a number or
     * three dashes must read as what it says rather than turn the page into a list, an ordered list or a
     * thematic break. The escaped character renders as itself, so nothing about the page reads differently.
     */
    @ParameterizedTest
    @CsvSource(delimiter = '|', quoteCharacter = '\'', textBlock = """
            '- an item'      | '\\- an item'
            '+ an item'      | '\\+ an item'
            '--- a break'    | '\\--- a break'
            '1. the first'   | '1\\. the first'
            '2) the second'  | '2\\) the second'
            'a - b'          | 'a - b'
            'version 1.0.0'  | 'version 1.0.0'
            """)
    void paragraph_whenItWouldOpenABlock_thenTheOpenerIsEscaped(String value, String expected) {
        assertThat(new MarkdownWriter().paragraph(value).text()).isEqualTo(expected + "\n");
    }

    /**
     * A heading is not a paragraph: after {@code ## } an ordered-list marker means nothing, and every arc42
     * chapter title begins with one. Escaping there would put a backslash in front of every chapter.
     */
    @Test
    void heading_whenItBeginsWithANumber_thenNothingIsEscaped() {
        assertThat(new MarkdownWriter().heading(1, "1. Introduction and Goals").text())
                .isEqualTo("# 1. Introduction and Goals\n");
    }

    @Test
    void importedDocument_keepsItsStructure_andShowsRawHtmlAsText() {
        String page = new MarkdownWriter()
                .importedDocument("## Why\n\n- one\n- two\n\nA <script>alert(1)</script> and a <br/>.")
                .text();

        assertThat(page).isEqualTo("""
                ### Why

                - one
                - two

                A &lt;script>alert(1)&lt;/script> and a &lt;br/>.
                """);
    }

    /** CommonMark does not decode an entity in code, so an escaped {@code <} there would show as {@code &lt;}. */
    @Test
    void importedDocument_whenItHasCode_thenTheCodeIsLeftAsItIs() {
        String page = new MarkdownWriter()
                .importedDocument("Use `List<String>` here, not <b>.\n\n```xml\n<order id=\"1\"/>\n```")
                .text();

        assertThat(page).isEqualTo("""
                Use `List<String>` here, not &lt;b>.

                ```xml
                <order id="1"/>
                ```
                """);
    }

    /** Left open, the fence would turn everything the page writes after the document into code. */
    @Test
    void importedDocument_whenAFenceIsLeftOpen_thenItIsClosedBeforeWhatFollows() {
        String page = new MarkdownWriter()
                .importedDocument("Before\n\n~~~~\nnever closed\n```")
                .paragraph("After")
                .text();

        assertThat(page).isEqualTo("""
                Before

                ~~~~
                never closed
                ```
                ~~~~

                After
                """);
    }

    @Test
    void importedDocument_whenAContainerIsLeftOpen_thenItIsClosed_andAStrayCloserIsEscaped() {
        String page = new MarkdownWriter()
                .importedDocument(":::\n\n::::note\n\n:::tip\n\nInside\n\n:::")
                .text();

        assertThat(page).isEqualTo("""
                \\:::

                ::::note

                :::tip

                Inside

                :::
                ::::
                """);
    }

    /** A target that is not absolute means nothing on this site, and the site build fails on a broken link. */
    @Test
    void importedDocument_whenALinkPointsIntoTheSite_thenOnlyItsTextIsKept() {
        String page = new MarkdownWriter()
                .importedDocument("""
                        See [the guide](guide.md), [the root](/), [an anchor](#how), [a site](https://example.org),
                        [mail](mailto:team@example.org "Mail"), [code](javascript:alert(1)) and ![a chart](chart.png).
                        [![a badge](badge.svg)](https://example.org/build) and `[not a link](here.md)`.
                        <https://example.org/plain> [ref]: ./elsewhere.md

                        [ref]: ./elsewhere.md
                        [ok]: https://example.org/ok
                        [^1]: A footnote.""")
                .text();

        assertThat(page).isEqualTo("""
                See the guide, the root, [an anchor](#how), [a site](https://example.org),
                [mail](mailto:team@example.org "Mail"), code and a chart.
                [a badge](https://example.org/build) and `[not a link](here.md)`.
                <https://example.org/plain> [ref]: ./elsewhere.md

                \\[ref]: ./elsewhere.md
                [ok]: https://example.org/ok
                [^1]: A footnote.
                """);
    }

    /** Hard-wrapped text splits links over lines, and CommonMark lets brackets and parentheses nest. */
    @Test
    void importedDocument_whenALinkWrapsOrNests_thenItIsStillFound() {
        String page = new MarkdownWriter()
                .importedDocument("""
                        See [the
                        guide](./guide.md), [[[nested]]](./x.md), [parens](./a((b)).md) and [kept](https://example.org/a_(b)).
                        [![logo](logo.png)](./home.md) and [wrapped](
                        https://example.org/next "Title").

                        [ref]:
                          ./elsewhere.md""")
                .text();

        assertThat(page).isEqualTo("""
                See the
                guide, [[nested]], parens and [kept](https://example.org/a_(b)).
                logo and [wrapped](
                https://example.org/next "Title").

                \\[ref]:
                  ./elsewhere.md
                """);
    }

    /** A code span may not cross out of a heading, so the backtick there must not hide the HTML after it. */
    @Test
    void importedDocument_whenABacktickIsUnmatchedInItsLine_thenItDoesNotHideHtml() {
        String page = new MarkdownWriter()
                .importedDocument("# Heading `\nA <b>bold</b> claim `\n\na `b\nc` <i>x</i> `d`")
                .text();

        assertThat(page).isEqualTo("""
                ## Heading `
                A &lt;b>bold&lt;/b> claim `

                a `b
                c` &lt;i>x&lt;/i> `d`
                """);
    }

    /** The page writes its own top-level heading, and a second one would compete with it. */
    @Test
    void importedDocument_movesEachHeadingOneLevelDown_butNotInCode() {
        String page = new MarkdownWriter()
                .importedDocument("# Title\n\n##### Five\n###### Six\n#hashtag\n\n```bash\n# a comment\n```")
                .text();

        assertThat(page).isEqualTo("""
                ## Title

                ###### Five
                ###### Six
                #hashtag

                ```bash
                # a comment
                ```
                """);
    }

    @Test
    void importedDocument_whenThereIsNothing_thenNothingIsWritten() {
        assertThat(new MarkdownWriter().importedDocument("  \n ").text()).isEmpty();
        assertThat(new MarkdownWriter().importedDocument(null).text()).isEmpty();
    }
}
